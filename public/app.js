const $ = (id) => document.getElementById(id);

const els = {
  location: $("location"), useGeo: $("useGeo"),
  commute: $("commute"), work: $("work"), household: $("household"),
  diet: $("diet"), energy: $("energy"), family: $("family"),
  go: $("go"), goText: $("go-text"), engine: $("engine"), engineText: $("engine-text"),
  aqiCard: $("aqiCard"), aqiLoc: $("aqiLoc"), aqiValue: $("aqiValue"), aqiLevel: $("aqiLevel"),
  aqiStandard: $("aqiStandard"), scaleLegend: $("scaleLegend"),
  gaugeFill: $("gaugeFill"), dominant: $("dominant"), pPM25: $("pPM25"), pO3: $("pO3"), pNO2: $("pNO2"),
  windows: $("windows"), wx: $("wx"), emptyState: $("emptyState"),
  planCard: $("planCard"), liveBadge: $("liveBadge"), headline: $("headline"),
  am: $("am"), day: $("day"), pm: $("pm"), indoor: $("indoor"), sust: $("sust"),
  sensitive: $("sensitive"), nextCheck: $("nextCheck"),
  impactCard: $("impactCard"), impDaily: $("impDaily"), impAnnual: $("impAnnual"),
  impTrees: $("impTrees"), impPM: $("impPM"), impactLine: $("impactLine"),
  errCard: $("errCard"), errText: $("errText"), loading: $("loading"),
  announce: $("announce"), engineFooter: $("engineFooter"),
};

// Gauge path is a semicircle of radius 96 -> visible length = π·96 ≈ 301.6.
const GAUGE_LEN = Math.PI * 96;
els.gaugeFill.style.strokeDasharray = GAUGE_LEN;
els.gaugeFill.style.strokeDashoffset = GAUGE_LEN;

// --- engine status pill ---
// The health endpoint deliberately hides key presence. The pill only reports
// the engine that actually produced a plan, set in render() from the response.
(async () => {
  try {
    const h = await (await fetch("/api/health")).json();
    els.engineText.textContent = "Ready";
    els.engine.title = `Default model: ${h.model || "configured model"}`;
  } catch {
    els.engineText.textContent = "Status unavailable";
  }
})();

function setEngine(live, engine) {
  if (live) {
    els.engine.className = "live";
    els.engineText.textContent = `GenAI · ${engine?.split(":")[1] || "live"}`;
    els.engineFooter.textContent = `Plan generated by Google Gemini (${engine?.split(":")[1] || "live"})`;
  } else {
    els.engine.className = "off";
    els.engineText.textContent = "Offline advisor";
    els.engineFooter.textContent = "Plan generated by the built-in offline advisor";
  }
}

// No hardcoded list: the user types the city, we send it verbatim. The server
// geocodes it for live AQI, and Gemini receives the raw text in the prompt.
function typedLocation() {
  const raw = els.location.value.trim();
  return raw || null;
}

// --- geolocation button ---
els.useGeo.addEventListener("click", () => {
  if (!navigator.geolocation) {
    els.announce.textContent = "Location is not supported by this browser. Type a city name instead.";
    return;
  }
  els.useGeo.setAttribute("aria-busy", "true");
  els.announce.textContent = "Finding your location…";
  navigator.geolocation.getCurrentPosition(
    (p) => {
      els.location.value = "My current location";
      els.location.dataset.geoLat = p.coords.latitude;
      els.location.dataset.geoLon = p.coords.longitude;
      els.useGeo.removeAttribute("aria-busy");
      els.announce.textContent = "Location found. Generate a plan to continue.";
    },
    () => {
      els.useGeo.removeAttribute("aria-busy");
      els.announce.textContent = "Location unavailable. Type a city name instead.";
    },
    { timeout: 8000 }
  );
});

function buildReq() {
  const name = typedLocation();
  let lat = null, lon = null;
  if (els.location.dataset.geoLat) {
    lat = +els.location.dataset.geoLat;
    lon = +els.location.dataset.geoLon;
  }
  return {
    locationName: name || "Current location", lat, lon,
    commute: els.commute.value, work: els.work.value,
    household: els.household.value, diet: els.diet.value,
    energy: els.energy.value, family: els.family.value,
  };
}

async function generate() {
  const req = buildReq();
  if (!req.locationName) return;
  els.go.disabled = true; els.goText.textContent = "Reading the air…";
  els.planCard.hidden = true; els.impactCard.hidden = true; els.emptyState.hidden = true;
  els.errCard.hidden = true; els.aqiCard.style.opacity = "0.55";
  els.loading.hidden = false;

  try {
    const r = await fetch("/api/plan", {
      method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(req),
    });
    const d = await r.json();
    if (!r.ok) throw new Error(d.error || "Request failed");
    render(d);
  } catch (e) {
    els.errCard.hidden = false;
    els.errText.textContent = e.message;
    els.aqiCard.style.opacity = "1";
    els.emptyState.hidden = false;
    els.announce.textContent = `Could not generate a plan: ${e.message}`;
  } finally {
    els.loading.hidden = true;
    els.go.disabled = false; els.goText.textContent = "Generate my plan";
  }
}

function render(d) {
  const a = d.aqi;

  // ---- live conditions ----
  els.aqiCard.style.opacity = "1";
  els.aqiLoc.textContent = [d.location.name, d.location.country].filter(Boolean).join(", ");
  els.aqiValue.textContent = a.aqi;
  els.aqiValue.style.color = a.color;
  // Dark text + a coloured dot keeps every category AA-legible on the pale badge.
  els.aqiLevel.replaceChildren();
  const badgeDot = document.createElement("i");
  badgeDot.style.background = a.color;
  els.aqiLevel.append(badgeDot, document.createTextNode(a.level));
  els.aqiLevel.style.background = a.bg;
  els.aqiLevel.style.borderColor = a.color + "44";
  els.aqiStandard.textContent = a.shortLabel || "AQI";
  els.aqiStandard.title = a.standardLabel || "Air Quality Index";
  els.scaleLegend.replaceChildren();
  (a.scale || []).forEach((l) => {
    const s = document.createElement("span");
    const dot = document.createElement("i"); dot.style.background = l.color;
    s.append(dot, document.createTextNode(l.name));
    s.title = `${l.name}: ${l.min}–${l.max}`;
    els.scaleLegend.appendChild(s);
  });
  els.gaugeFill.style.stroke = a.color;
  els.gaugeFill.style.strokeDashoffset = GAUGE_LEN * (1 - Math.max(0, Math.min(1, a.aqi / 500)));
  els.dominant.textContent = a.dominantPollutant || "—";
  els.pPM25.textContent = a.poll.pm2_5 != null ? `${a.poll.pm2_5} µg/m³` : "—";
  els.pO3.textContent = a.poll.ozone != null ? `${a.poll.ozone} µg/m³` : "—";
  els.pNO2.textContent = a.poll.no2 != null ? `${a.poll.no2} µg/m³` : "—";

  // best time-of-day windows
  els.windows.replaceChildren();
  if (a.bestWindows?.length) {
    const label = document.createElement("div");
    label.className = "win-label";
    label.innerHTML = '<svg viewBox="0 0 18 18" width="14" height="14"><path d="M9 1.5 10.6 6 15 7.5l-4.4 1.5L9 13.5 7.4 9 3 7.5 7.4 6 9 1.5Z" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linejoin="round"/></svg>';
    label.append("Cleanest hours (lowest PM2.5)");
    const chips = document.createElement("div"); chips.className = "win";
    a.bestWindows.forEach((c, i) => {
      const s = document.createElement("span");
      s.className = "chip" + (i === 0 ? " primary" : "");
      s.textContent = `${c.hour} · PM2.5 ≈ ${Math.round(c.pm25)}`;
      chips.appendChild(s);
    });
    els.windows.append(label, chips);
  } else {
    els.windows.innerHTML = '<span class="hint">24h windows unavailable</span>';
  }

  // weather in the header slot
  els.wx.textContent = d.weather
    ? `${d.weather.temp}°C · feels ${d.weather.feelsLike}°C · ${d.weather.humidity}% humidity · ${d.weather.wind} km/h wind`
    : "Live conditions";

  // ---- plan ----
  const p = d.plan;
  els.planCard.hidden = false;
  els.liveBadge.hidden = !d.live;
  setEngine(!!d.live, d.engine);
  if (d.live) els.liveBadge.textContent = "GenAI · " + (String(d.engine || "").split(":")[1] || "live");
  els.headline.textContent = p.headline || "";
  els.announce.textContent = `Plan ready for ${els.aqiLoc.textContent}. ${a.level} air, AQI ${a.aqi}.`;
  fillList(els.am, p.routine?.am);
  fillList(els.day, p.routine?.day);
  fillList(els.pm, p.routine?.pm);
  fillList(els.indoor, p.indoorAir);
  fillList(els.sust, p.sustainability);

  // sensitive-family callout (fill the element already in the DOM — no re-appending)
  fillCallout(els.sensitive, "amber", "For sensitive family members", p.sensitiveNotes || []);

  // next-check callout
  if (p.nextCheck) {
    els.nextCheck.hidden = false;
    fillCallout(els.nextCheck, "blue", "Next check", [p.nextCheck]);
  } else {
    els.nextCheck.hidden = true;
  }

  // ---- impact ----
  const imp = d.impact || {};
  els.impactCard.hidden = false;
  els.impDaily.textContent = imp.dailyCO2SavedKg ?? "—";
  els.impAnnual.textContent = imp.annualCO2SavedKg ?? "—";
  els.impTrees.textContent = imp.treesEquivalentPerYear ?? "—";

  // Server-computed, explicitly illustrative HEPA figure — never fabricated
  // "street-level AQI cut" percentages.
  const hepaPct = imp.indoorHEPAReductionPct ?? 70;
  els.impPM.textContent = `≈${hepaPct}%`;

  els.impactLine.replaceChildren();
  const notes = [];
  if (imp.localAQIBenefit) notes.push(["#0d9488", "Local air", imp.localAQIBenefit]);
  if (imp.indoorAirBenefit) notes.push(["#2563eb", "Indoors", imp.indoorAirBenefit]);
  if (!notes.length) notes.push(["#0d9488", "Impact", "Your routine reduces your household's contribution to local air pollution."]);
  notes.forEach(([color, label, text]) => {
    const row = document.createElement("div"); row.className = "impact-note";
    const dot = document.createElement("i"); dot.style.background = color;
    const body = document.createElement("span");
    const bold = document.createElement("b"); bold.textContent = label + ": ";
    body.append(bold, document.createTextNode(text));
    row.append(dot, body);
    els.impactLine.appendChild(row);
  });
}

/* ---------- rendering helpers ---------- */

function fillList(el, items) {
  el.replaceChildren();
  (items || []).forEach((it) => el.appendChild(makeItem(it.title, it.detail, it.impact, it.why)));
}

function makeItem(title, detail, impact, why) {
  const wrap = document.createElement("div"); wrap.className = "item";

  const t = document.createElement("div"); t.className = "item-title"; t.textContent = title || "";
  wrap.appendChild(t);

  if (detail) { const p = document.createElement("p"); p.className = "item-detail"; p.textContent = detail; wrap.appendChild(p); }

  if (impact) {
    const i = document.createElement("div"); i.className = "item-impact";
    i.innerHTML = '<svg viewBox="0 0 18 18" width="14" height="14"><path d="M14 2.5C7 2.8 3.5 6 3.5 10.2A4.2 4.2 0 0 0 7.7 14.4C12.6 14.4 14 9 14 2.5Z" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linejoin="round"/><path d="M4 14.5c2-4 4.6-6 8.4-7.6" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round"/></svg>';
    const span = document.createElement("span"); span.textContent = impact;
    i.appendChild(span); wrap.appendChild(i);
  }

  if (why) { const w = document.createElement("p"); w.className = "item-why"; w.textContent = "Why: " + why; wrap.appendChild(w); }
  return wrap;
}

function fillCallout(el, tone, title, items) {
  el.className = "callout " + tone;
  el.replaceChildren();
  const h = document.createElement("div"); h.className = "callout-title";
  h.innerHTML = '<svg viewBox="0 0 18 18" width="14" height="14"><path d="M9 1.8 16 4.6v4.2c0 3.6-2.7 6.4-7 8-4.3-1.6-7-4.4-7-8V4.6L9 1.8Z" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linejoin="round"/><path d="m6.5 9 1.8 1.8 3.3-3.6" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>';
  h.append(title);
  el.appendChild(h);
  if (items.length === 1) {
    const p = document.createElement("div"); p.textContent = items[0]; el.appendChild(p);
  } else {
    const ul = document.createElement("ul");
    items.forEach((n) => { const li = document.createElement("li"); li.textContent = n; ul.appendChild(li); });
    el.appendChild(ul);
  }
}

els.go.addEventListener("click", generate);
els.location.addEventListener("keydown", (e) => { if (e.key === "Enter") generate(); });
