const GAUGE_RADIUS = 96;
const GAUGE_LEN = Math.PI * GAUGE_RADIUS; // semicircle length in SVG units
const AQI_MAX = 500; // matches the clamp in the server's AQI model

const ICONS = Object.freeze({
  spark: '<svg viewBox="0 0 18 18" width="14" height="14"><path d="M9 1.5 10.6 6 15 7.5l-4.4 1.5L9 13.5 7.4 9 3 7.5 7.4 6 9 1.5Z" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linejoin="round"/></svg>',
  leaf: '<svg viewBox="0 0 18 18" width="14" height="14"><path d="M14 2.5C7 2.8 3.5 6 3.5 10.2A4.2 4.2 0 0 0 7.7 14.4C12.6 14.4 14 9 14 2.5Z" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linejoin="round"/><path d="M4 14.5c2-4 4.6-6 8.4-7.6" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round"/></svg>',
  shield: '<svg viewBox="0 0 18 18" width="14" height="14"><path d="M9 1.8 16 4.6v4.2c0 3.6-2.7 6.4-7 8-4.3-1.6-7-4.4-7-8V4.6L9 1.8Z" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linejoin="round"/><path d="m6.5 9 1.8 1.8 3.3-3.6" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>',
});

els.gaugeFill.style.strokeDasharray = GAUGE_LEN;
els.gaugeFill.style.strokeDashoffset = GAUGE_LEN;

// Static hosts cannot run the Express API. Point the UI at a deployed backend
// with ?api=https://your-backend.example or window.AURA_API_BASE before app.js.
const API_BASE = (new URLSearchParams(location.search).get("api") || window.AURA_API_BASE || "")
  .replace(/\/+$/, "");

/** Never let an HTML 404 page surface as a raw JSON parse error. */
async function apiJson(path, options) {
  const res = await fetch(API_BASE + path, options);
  const body = await res.text();
  let data;
  try {
    data = JSON.parse(body);
  } catch (cause) {
    const message = res.ok
      ? "The server returned an unexpected response. Check that the API is deployed."
      : `API unavailable (HTTP ${res.status}). Check that the backend is running.`;
    throw new Error(message, { cause });
  }
  if (!res.ok) throw new Error(data.error || `Request failed (HTTP ${res.status})`);
  return data;
}

/** The health endpoint hides key presence; the pill reflects the engine that ran. */
function setEngine(live, engine) {
  if (live) {
    els.engine.className = "live";
    els.engineText.textContent = `GenAI · ${engineLabel(engine)}`;
    els.engineFooter.textContent = `Plan generated by Google Gemini (${engineLabel(engine)})`;
  } else {
    els.engine.className = "off";
    els.engineText.textContent = "Offline advisor";
    els.engineFooter.textContent = "Plan generated by the built-in offline advisor";
  }
}

/** Read the model name out of an "engine:model" identifier. */
function engineLabel(engine) {
  return String(engine || "").split(":")[1] || "live";
}

/** Build the small coloured status dots used by the badge, legend and notes. */
function coloredDot(color) {
  const dot = document.createElement("i");
  dot.style.background = color;
  return dot;
}

const formatConcentration = (value) => (value != null ? `${value} µg/m³` : "—");

(async () => {
  try {
    const health = await apiJson("/api/health");
    els.engineText.textContent = "Ready";
    els.engine.title = `Default model: ${health.model || "configured model"}`;
  } catch (err) {
    els.engineText.textContent = "Status unavailable";
  }
})();

// No hardcoded list: the user types the city, we send it verbatim. The server
// geocodes it for live AQI, and Gemini receives the raw text in the prompt.
function typedLocation() {
  return els.location.value.trim() || null;
}

els.useGeo.addEventListener("click", () => {
  if (!navigator.geolocation) {
    els.announce.textContent = "Location is not supported by this browser. Type a city name instead.";
    return;
  }
  els.useGeo.setAttribute("aria-busy", "true");
  els.announce.textContent = "Finding your location…";
  navigator.geolocation.getCurrentPosition(
    (position) => {
      els.location.value = "My current location";
      els.location.dataset.geoLat = position.coords.latitude;
      els.location.dataset.geoLon = position.coords.longitude;
      els.useGeo.removeAttribute("aria-busy");
      els.announce.textContent = "Location found. Generate a plan to continue.";
    },
    () => {
      els.useGeo.removeAttribute("aria-busy");
      els.announce.textContent = "Location unavailable. Type a city name instead.";
    },
    { timeout: 8000 }
  );
});

function buildReq() {
  const name = typedLocation();
  let lat = null;
  let lon = null;
  if (els.location.dataset.geoLat) {
    lat = +els.location.dataset.geoLat;
    lon = +els.location.dataset.geoLon;
  }
  return {
    locationName: name || "Current location", lat, lon,
    commute: els.commute.value, work: els.work.value,
    household: els.household.value, diet: els.diet.value,
    energy: els.energy.value, family: els.family.value,
  };
}

async function generate() {
  const req = buildReq();
  if (!req.locationName) return;
  els.go.disabled = true;
  els.goText.textContent = "Reading the air…";
  els.planCard.hidden = true;
  els.impactCard.hidden = true;
  els.emptyState.hidden = true;
  els.errCard.hidden = true;
  els.aqiCard.style.opacity = "0.55";
  els.loading.hidden = false;

  try {
    const data = await apiJson("/api/plan", {
      method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(req),
    });
    render(data);
  } catch (err) {
    els.errCard.hidden = false;
    els.errText.textContent = err.message;
    els.aqiCard.style.opacity = "1";
    els.emptyState.hidden = false;
    els.announce.textContent = `Could not generate a plan: ${err.message}`;
  } finally {
    els.loading.hidden = true;
    els.go.disabled = false;
    els.goText.textContent = "Generate my plan";
  }
}

/* ---------- rendering ---------- */

function render(data) {
  renderAqi(data);
  renderPlan(data);
  renderImpact(data);
}

function renderAqi(data) {
  const a = data.aqi;
  els.aqiCard.style.opacity = "1";
  els.aqiLoc.textContent = [data.location.name, data.location.country].filter(Boolean).join(", ");
  els.aqiValue.textContent = a.aqi;
  els.aqiValue.style.color = a.color;
  // Dark text + a coloured dot keeps every category AA-legible on the pale badge.
  els.aqiLevel.replaceChildren(coloredDot(a.color), document.createTextNode(a.level));
  els.aqiLevel.style.background = a.bg;
  els.aqiLevel.style.borderColor = a.color + "44";
  els.aqiStandard.textContent = a.shortLabel || "AQI";
  els.aqiStandard.title = a.standardLabel || "Air Quality Index";

  els.scaleLegend.replaceChildren();
  (a.scale || []).forEach((level) => {
    const span = document.createElement("span");
    span.append(coloredDot(level.color), document.createTextNode(level.name));
    span.title = `${level.name}: ${level.min}–${level.max}`;
    els.scaleLegend.appendChild(span);
  });

  els.gaugeFill.style.stroke = a.color;
  const fraction = Math.max(0, Math.min(1, a.aqi / AQI_MAX));
  els.gaugeFill.style.strokeDashoffset = GAUGE_LEN * (1 - fraction);
  els.dominant.textContent = a.dominantPollutant || "—";
  els.pPM25.textContent = formatConcentration(a.poll.pm2_5);
  els.pO3.textContent = formatConcentration(a.poll.ozone);
  els.pNO2.textContent = formatConcentration(a.poll.no2);
  renderWindows(a.bestWindows);

  els.wx.textContent = data.weather
    ? `${data.weather.temp}°C · feels ${data.weather.feelsLike}°C · ${data.weather.humidity}% humidity · ${data.weather.wind} km/h wind`
    : "Live conditions";
}

function renderWindows(windows) {
  els.windows.replaceChildren();
  if (!windows?.length) {
    els.windows.innerHTML = '<span class="hint">24h windows unavailable</span>';
    return;
  }
  const label = document.createElement("div");
  label.className = "win-label";
  label.innerHTML = ICONS.spark; // static, trusted markup
  label.append("Cleanest hours (lowest PM2.5)");

  const chips = document.createElement("div");
  chips.className = "win";
  windows.forEach((window, index) => {
    const chip = document.createElement("span");
    chip.className = "chip" + (index === 0 ? " primary" : "");
    chip.textContent = `${window.hour} · PM2.5 ≈ ${Math.round(window.pm25)}`;
    chips.appendChild(chip);
  });
  els.windows.append(label, chips);
}

function renderPlan(data) {
  const plan = data.plan;
  els.planCard.hidden = false;
  els.liveBadge.hidden = !data.live;
  setEngine(!!data.live, data.engine);
  if (data.live) els.liveBadge.textContent = "GenAI · " + engineLabel(data.engine);
  els.headline.textContent = plan.headline || "";
  els.announce.textContent = `Plan ready for ${els.aqiLoc.textContent}. ${data.aqi.level} air, AQI ${data.aqi.aqi}.`;

  fillList(els.am, plan.routine?.am);
  fillList(els.day, plan.routine?.day);
  fillList(els.pm, plan.routine?.pm);
  fillList(els.indoor, plan.indoorAir);
  fillList(els.sust, plan.sustainability);

  fillCallout(els.sensitive, "amber", "For sensitive family members", plan.sensitiveNotes || []);
  if (plan.nextCheck) {
    els.nextCheck.hidden = false;
    fillCallout(els.nextCheck, "blue", "Next check", [plan.nextCheck]);
  } else {
    els.nextCheck.hidden = true;
  }
}

function renderImpact(data) {
  const impact = data.impact || {};
  els.impactCard.hidden = false;
  els.impDaily.textContent = impact.dailyCO2SavedKg ?? "—";
  els.impAnnual.textContent = impact.annualCO2SavedKg ?? "—";
  els.impTrees.textContent = impact.treesEquivalentPerYear ?? "—";
  // The server recomputes this figure; never invent a percentage in the browser.
  els.impPM.textContent = impact.indoorHEPAReductionPct != null
    ? `≈${impact.indoorHEPAReductionPct}%`
    : "—";

  els.impactLine.replaceChildren();
  const notes = [];
  if (impact.localAQIBenefit) notes.push(["#0d9488", "Local air", impact.localAQIBenefit]);
  if (impact.indoorAirBenefit) notes.push(["#2563eb", "Indoors", impact.indoorAirBenefit]);
  if (!notes.length) {
    notes.push(["#0d9488", "Impact", "Your routine reduces your household's contribution to local air pollution."]);
  }
  notes.forEach(([color, label, text]) => els.impactLine.appendChild(impactNote(color, label, text)));
}

function impactNote(color, label, text) {
  const row = document.createElement("div");
  row.className = "impact-note";
  const body = document.createElement("span");
  const bold = document.createElement("b");
  bold.textContent = label + ": ";
  body.append(bold, document.createTextNode(text));
  row.append(coloredDot(color), body);
  return row;
}

function fillList(el, items) {
  el.replaceChildren();
  (items || []).forEach((item) => el.appendChild(makeItem(item.title, item.detail, item.impact, item.why)));
}

function makeItem(title, detail, impact, why) {
  const wrap = document.createElement("div");
  wrap.className = "item";

  const heading = document.createElement("div");
  heading.className = "item-title";
  heading.textContent = title || "";
  wrap.appendChild(heading);

  if (detail) {
    const paragraph = document.createElement("p");
    paragraph.className = "item-detail";
    paragraph.textContent = detail;
    wrap.appendChild(paragraph);
  }

  if (impact) {
    const badge = document.createElement("div");
    badge.className = "item-impact";
    badge.innerHTML = ICONS.leaf; // static, trusted markup
    const text = document.createElement("span");
    text.textContent = impact;
    badge.appendChild(text);
    wrap.appendChild(badge);
  }

  if (why) {
    const paragraph = document.createElement("p");
    paragraph.className = "item-why";
    paragraph.textContent = "Why: " + why;
    wrap.appendChild(paragraph);
  }
  return wrap;
}

function fillCallout(el, tone, title, items) {
  el.className = "callout " + tone;
  el.replaceChildren();
  const heading = document.createElement("div");
  heading.className = "callout-title";
  heading.innerHTML = ICONS.shield; // static, trusted markup
  heading.append(title);
  el.appendChild(heading);

  if (items.length === 1) {
    const line = document.createElement("div");
    line.textContent = items[0];
    el.appendChild(line);
  } else {
    const list = document.createElement("ul");
    items.forEach((note) => {
      const item = document.createElement("li");
      item.textContent = note;
      list.appendChild(item);
    });
    el.appendChild(list);
  }
}

els.go.addEventListener("click", generate);
els.location.addEventListener("keydown", (event) => {
  if (event.key === "Enter") generate();
});
